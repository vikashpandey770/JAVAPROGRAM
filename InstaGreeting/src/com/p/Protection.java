package com.p;

public class Protection {

	int a=30;
	private int ab=34;
	protected int as=33;
	public int ac=23;
	
	public Protection() {
		System.out.println("this is a constructor");
		System.out.println("this a:"+a);
		System.out.println("this ab:"+ab);
		System.out.println("this as:"+as);
		System.out.println("this ac:"+ac);
	}	
}